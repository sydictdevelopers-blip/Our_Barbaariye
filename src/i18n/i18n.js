// keep <html dir="..."> in sync for RTL languages
const applyDir = (lng) => {
  const isRtl = lng === 'ar';
  document.documentElement.setAttribute('dir', isRtl ? 'rtl' : 'ltr');
  document.documentElement.setAttribute('lang', lng);
};
applyDir(i18n.language);
i18n.on('languageChanged', applyDir);

/**
 * Translate a fixed-vocabulary database value (status, type, lock state, etc.)
 * using the current language. Falls back to the original value when no key matches.
 * Components that call this should also `useTranslation()` so they re-render on
 * language change — `tDb` itself doesn't subscribe.
 *
 *   tDb('Active')   // → 'Firfircoon' / 'Active' / 'نشط'
 *   tDb('Adnan')    // → 'Adnan' (no key match → identity)
 */
export function tDb(value) {
  if (value == null || value === '') return value;
  const s = String(value);
  const translated = i18n.t(`dbValues.${s}`, { defaultValue: '' });
  return translated || s;
}

