// keep <html dir="..."> in sync for RTL languages
const applyDir = (lng) => {
  const isRtl = lng === 'ar';
  document.documentElement.setAttribute('dir', isRtl ? 'rtl' : 'ltr');
  document.documentElement.setAttribute('lang', lng);
};
applyDir(i18n.language);
i18n.on('languageChanged', applyDir);

